import { KNOWLEDGE_BASE_POLICIES } from './knowledgeBase';

export async function generateAIDraft(customerMessage: string): Promise<string> {

  if (process.env.GROQ_API_KEY) {
    try {
      const { default: Groq } = await import('groq-sdk');
      const groq = new Groq({ apiKey: process.env.GROQ_API_KEY.trim() });
      
      const response = await groq.chat.completions.create({
        model: 'openai/gpt-oss-120b', 
        messages: [
          {
            role: 'system',
            content: `You are a helpful, professional customer support agent for Verdant & Co. Use ONLY the following policy guidelines to draft a concise, empathetic response. Do not use generic bracketed placeholders like [Customer Name].\n${KNOWLEDGE_BASE_POLICIES}`
          },
          { role: 'user', content: customerMessage }
        ],
        temperature: 0.2,
      });

      const draft = response.choices[0]?.message?.content?.trim();
      if (draft) {
        console.log("SUCCESS: Response generated live by Groq API!");
        return draft;
      }
    } catch (err: any) {
      console.warn("Groq API Call Failed! Reason:", err?.message || err);
    }
  }

  console.log("FALLBACK: Response generated by local policy matching engine.");
  const msg = customerMessage.toLowerCase();

  if (msg.includes('cancel') || msg.includes('late') || msg.includes('delay') || msg.includes('money back')) {
    return "I sincerely apologize for the delay and frustrating experience! Orders can be cancelled for a full refund if they have not yet shipped. Please provide your order number so I can check your shipping status and process a cancellation or trace your shipment immediately.";
  }
  if (msg.includes('broken') || msg.includes('damaged') || msg.includes('jar') || msg.includes('leak')) {
    return "I'm so sorry to hear that your item arrived broken! Since opened or damaged items are covered under our exception policy, please reply with a photo of the damaged item so we can process a free replacement immediately.";
  }
  if (msg.includes('return') || msg.includes('refund') || msg.includes('allergic')) {
    return "Hello! Returns are accepted within 7 days of delivery for unopened products. Opened items are accepted only if damaged or if the wrong item was sent. How can we assist you further?";
  }
  if (msg.includes('address') || msg.includes('change')) {
    return "Hello! The delivery address can be changed only before the order has shipped, and only if requested within 12 hours of placing the order. Please let us know your order details if placed recently.";
  }
  if (msg.includes('cash on delivery') || msg.includes('cod')) {
    return "Hi! Cash on delivery is available for orders under ₹3,000, with a ₹50 fee.";
  }
  if (msg.includes('ship') || msg.includes('deliver') || msg.includes('arrived')) {
    return "Hi there! Orders ship within 24 hours (Mon-Sat). Delivery takes 3-5 business days in metro cities and 5-8 business days elsewhere in India.";
  }

  return "Thank you for reaching out to Verdant & Co. A support representative will review your message shortly.";
}